"""Reviewed answers and a private follow-up queue on the existing database."""

import json
import re
import unicodedata
from contextlib import closing
from datetime import datetime, timezone
from urllib.parse import urlsplit


def normalized_question(value):
    text = str(value).strip().lower()
    text = ''.join(c for c in text if not unicodedata.combining(c))
    for old, new in (("أ", "ا"), ("إ", "ا"), ("آ", "ا"), ("ة", "ه"), ("ى", "ي")):
        text = text.replace(old, new)
    return ' '.join(re.sub(r'[^\w\s]', ' ', text).split())


def validated_faq(payload):
    if not isinstance(payload, dict):
        raise ValueError("FAQ must be an object")
    item = {}
    for key, limit in {"question": 300, "answer": 2000, "source_title": 120}.items():
        value = payload.get(key)
        if not isinstance(value, str) or not value.strip() or len(value) > limit:
            raise ValueError(f"{key} is required; maximum {limit} characters")
        item[key] = value.strip()
    aliases = payload.get("aliases", [])
    if not isinstance(aliases, list) or len(aliases) > 20 or any(
        not isinstance(a, str) or not a.strip() or len(a) > 300 for a in aliases
    ):
        raise ValueError("aliases must contain at most 20 nonempty questions")
    item["aliases"] = [a.strip() for a in aliases]
    if not all(normalized_question(q) for q in [item["question"], *item["aliases"]]):
        raise ValueError("questions must contain words")
    approved = payload.get("approved", False)
    if not isinstance(approved, bool):
        raise ValueError("approved must be a boolean")
    item["approved"] = approved
    url = payload.get("source_url", "")
    if not isinstance(url, str) or len(url) > 1000 or any(c.isspace() for c in url):
        raise ValueError("source_url must be an HTTPS URL or empty")
    if url:
        parsed = urlsplit(url)
        if parsed.scheme != "https" or not parsed.hostname or parsed.username or parsed.password:
            raise ValueError("source_url must be HTTPS without credentials")
    item["source_url"] = url
    return item


def find_reviewed_answer(text, items):
    question = normalized_question(text)
    matches = [item for item in items if item["approved"] and question in {
        normalized_question(q) for q in [item["question"], *item["aliases"]]
    }]
    # Conflicting entries need review instead of arbitrary policy selection.
    if len(matches) != 1:
        return None
    item = matches[0]
    english = bool(re.search(r'[A-Za-z]', text)) and not re.search(r'[\u0600-\u06ff]', text)
    source = "Source" if english else "المصدر"
    reply = f"{item['answer']}\n\n{source}: {item['source_title']}"
    if item["source_url"]:
        reply += f"\n{item['source_url']}"
    return reply


