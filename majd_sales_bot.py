@app.post("/majd/webhook")
def telegram_webhook():
    if WEBHOOK_SECRET:
        supplied = request.headers.get("X-Telegram-Bot-Api-Secret-Token", "")
        if supplied != WEBHOOK_SECRET:
            return jsonify({"error": "unauthorized"}), 401

    update = request.get_json(silent=True) or {}
    update_id = update.get("update_id")
    if update_id is not None:
        if update_id in PROCESSED_UPDATES:
            return jsonify({"ok": True})
        PROCESSED_UPDATES.add(update_id)
        if len(PROCESSED_UPDATES) > 5000:
            for old_id in sorted(PROCESSED_UPDATES)[:1000]:
                PROCESSED_UPDATES.discard(old_id)

    message = update.get("message") or {}
    text = str(message.get("text") or "").strip()
    chat_id = (message.get("chat") or {}).get("id")
    sender = message.get("from") or {}
    username = sender.get("username")

    if not chat_id or not text:
        return jsonify({"ok": True})

    if text.startswith("/myid") or text.startswith("/register_owner"):
        telegram_send(
            chat_id,
            f"رقم حسابك الداخلي هو:\n{chat_id}\n"
            "أرسله لمجد داخل ChatGPT ليتم تسجيلك كمالك دائم.",
        )
        return jsonify({"ok": True})

    if text.startswith("/start"):
        SCRIPTED_STATES[str(chat_id)] = {"last_topic": "welcome", "lead": {}}
        greeting = (
            "أهلاً بك، أنا مجد، مساعد مبيعات ذكي لوكيل العملاء V6. "
            "أستخدم الذكاء الاصطناعي لأسئلة البيع العامة، أما بيانات الاتصال فتعالج محلياً. "
            "أستطيع شرح المنتج والديمو والتخصيص والسعر. ما نوع نشاطك؟"
        )
        save_message(chat_id, username, "assistant", greeting)
        telegram_send(chat_id, greeting)
        return jsonify({"ok": True})

    save_message(chat_id, username, "user", text)
    try:
        reply = ai_reply(chat_id, username, text)
        save_message(chat_id, username, "assistant", reply)
        telegram_send(chat_id, reply)
    except Exception:
        telegram_send(chat_id, "صار عطل مؤقت أثناء تجهيز الرد. حاول بعد قليل من فضلك.")
        # Always acknowledge Telegram updates; a 500 makes Telegram resend the
        # same update and causes duplicate customer-facing error messages.
        return jsonify({"ok": True})
    return jsonify({"ok": True})

